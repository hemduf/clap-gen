pub(crate) fn header(ir: &CanonicalIr) -> String {
    let mut output = String::from(BANNER);
    output.push_str("#pragma once\n\n#include <array>\n#include <cstdint>\n");
    for header in capability_headers(ir) {
        writeln!(&mut output, "#include <{header}>").expect("writing to String cannot fail");
    }
    output.push_str(TYPE_DECLARATIONS);
    append_array_declarations(&mut output, ir);
    output.push_str("\n} // namespace clapgen::generated\n");
    output
}

fn append_array_declarations(output: &mut String, ir: &CanonicalIr) {
    output.push_str(
        "extern const PluginMetadata plugin;\nextern const ProcessorMetadata processor;\n",
    );
    append_array_declaration(output, "ParameterMetadata", "parameters", ir.parameters().len());
    append_array_declaration(output, "AudioPortMetadata", "audio_ports", ir.audio_ports().len());
    append_array_declaration(output, "NotePortMetadata", "note_ports", ir.note_ports().len());
    append_array_declaration(output, "NoteNameMetadata", "note_names", ir.note_names().len());
    append_array_declaration(output, "StateFieldMetadata", "state_fields", ir.state_fields().len());
    append_array_declaration(output, "GuiApiMetadata", "gui_apis", ir.gui_apis().len());
    append_array_declaration(
        output,
        "PresetLocationMetadata",
        "preset_locations",
        ir.preset_locations().len(),
    );
    append_array_declaration(
        output,
        "PresetFormatMetadata",
        "preset_formats",
        ir.preset_formats().len(),
    );
    append_array_declaration(output, "FactoryMetadata", "factories", ir.factories().len());
    append_array_declaration(
        output,
        "ExtensionMetadata",
        "extensions",
        ir.stable_extension_items().len() + ir.draft_extension_items().len(),
    );
}

fn append_array_declaration(output: &mut String, type_name: &str, name: &str, count: usize) {
    writeln!(output, "extern const std::array<{type_name}, {count}> {name};")
        .expect("writing to String cannot fail");
}

pub(crate) fn source(ir: &CanonicalIr) -> String {
    let mut output = String::from(BANNER);
    output.push_str("#include \"clapgen_metadata.hpp\"\n\nnamespace clapgen::generated {\n\n");
    output.push_str(&render_plugin(ir));
    output.push_str(&render_processor(ir));
    output.push_str(&render_parameters(ir));
    output.push_str(&render_audio_ports(ir));
    output.push_str(&render_note_ports(ir));
    output.push_str(&render_note_names(ir));
    output.push_str(&render_state_fields(ir));
    output.push_str(&render_gui_apis(ir));
    output.push_str(&render_preset_locations(ir));
    output.push_str(&render_preset_formats(ir));
    output.push_str(&render_factories(ir));
    output.push_str(&render_extensions(ir));
    output.push_str("} // namespace clapgen::generated\n");
    output
}

fn capability_headers(ir: &CanonicalIr) -> BTreeSet<&'static str> {
    ir.stable_extension_items()
        .iter()
        .chain(ir.draft_extension_items())
        .filter_map(|extension| extension.header)
        .collect()
}

fn render_plugin(ir: &CanonicalIr) -> String {
    let plugin = ir.plugin();
    format!(
        "const PluginMetadata plugin{{{}, {}, {}, {}, {}, {}, {}, {}, {}}};\n\n",
        cpp_string(&plugin.id),
        cpp_string(&plugin.name),
        cpp_string(&plugin.vendor),
        cpp_string(&plugin.version),
        optional_cpp_string(plugin.url.as_deref()),
        optional_cpp_string(plugin.manual_url.as_deref()),
        optional_cpp_string(plugin.support_url.as_deref()),
        optional_cpp_string(plugin.description.as_deref()),
        cpp_string(&plugin.features.join(",")),
    )
}

fn render_processor(ir: &CanonicalIr) -> String {
    let processor = ir.processor();
    format!(
        "const ProcessorMetadata processor{{{}, {}}};\n\n",
        cpp_string(&processor.class),
        cpp_string(&processor.features.join(",")),
    )
}

fn render_parameters(ir: &CanonicalIr) -> String {
    let items = ir
        .parameters()
        .iter()
        .map(|parameter| {
            format!(
                "    ParameterMetadata{{{}, {}, {}, {}, {}, {}, {}, {}, {}}},",
                cpp_string(&parameter.id),
                cpp_string(&parameter.name),
                parameter.min,
                parameter.max,
                parameter.default,
                cpp_string(&parameter.flags.join(",")),
                optional_cpp_string(parameter.unit.as_deref()),
                parameter.steps.is_some(),
                parameter.steps.unwrap_or_default(),
            )
        })
        .collect::<Vec<_>>();
    render_array("ParameterMetadata", "parameters", &items)
}

