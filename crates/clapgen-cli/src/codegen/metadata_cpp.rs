fn render_extensions(ir: &CanonicalIr) -> String {
    let mut extensions = ir
        .stable_extension_items()
        .iter()
        .map(|extension| (false, extension))
        .chain(ir.draft_extension_items().iter().map(|extension| (true, extension)))
        .collect::<Vec<_>>();
    extensions.sort_by(|(left_draft, left), (right_draft, right)| {
        (left_draft, &left.id, &left.version).cmp(&(right_draft, &right.id, &right.version))
    });
    let items = extensions
        .into_iter()
        .map(|(draft, extension)| render_extension(extension, draft))
        .collect::<Vec<_>>();
    render_array("ExtensionMetadata", "extensions", &items)
}

fn render_extension(extension: &ExtensionIr, draft: bool) -> String {
    format!(
        "    ExtensionMetadata{{{}, {}, {}, {}}},",
        cpp_string(&extension.id),
        optional_cpp_string(extension.version.as_deref()),
        draft,
        optional_cpp_string(extension.header),
    )
}

fn render_array(type_name: &str, name: &str, items: &[String]) -> String {
    if items.is_empty() {
        return format!("const std::array<{type_name}, 0> {name}{{}};\n\n");
    }
    format!(
        "const std::array<{type_name}, {}> {name}{{{{\n{}\n}}}};\n\n",
        items.len(),
        items.join("\n"),
    )
}

fn optional_cpp_string(value: Option<&str>) -> String {
    value.map_or_else(|| "nullptr".to_owned(), cpp_string)
}
